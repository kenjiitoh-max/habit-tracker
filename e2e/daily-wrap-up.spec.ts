import { expect, test } from '@playwright/test'

test('today recap updates after saving, survives reload and rolls over at JST midnight', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.clock.install({ time: new Date('2026-06-03T14:59:00Z') })
  await page.addInitScript(() => {
    if (localStorage.getItem('recap-seeded')) return
    localStorage.setItem('habit-tracker:v1', JSON.stringify({ habits: [], logs: [] }))
    localStorage.setItem('habit-tracker:study-time:v1', JSON.stringify({ '2026-06-01': { shadoten: 10 } }))
    localStorage.setItem('recap-seeded', 'true')
  })
  await page.goto('./')
  const card = page.getByRole('region', { name: '今日の締め', exact: true })
  await expect(card).toContainText('まだ今日の記録はありません')
  await expect(card).toContainText('今日 +0 XP')
  await card.scrollIntoViewIfNeeded()
  if (process.env.RECAP_SCREENSHOTS) await page.screenshot({ path: '/home/ubuntu/screens/recap-empty.png' })
  await page.getByRole('spinbutton', { name: 'シャドテン（分）' }).fill('15')
  await page.getByRole('button', { name: 'シャドテンを保存' }).tap()
  await expect(card).toContainText('今日 +40 XP')
  await expect(card).toContainText('今日は自己ベスト更新なし')
  await expect(card).toContainText('1日連続')
  await card.scrollIntoViewIfNeeded()
  if (process.env.RECAP_SCREENSHOTS) await page.screenshot({ path: '/home/ubuntu/screens/recap-no-pr.png' })
  const workout = page.getByRole('region', { name: '今日の筋トレ' })
  await page.locator('#workout-exercise').selectOption('preset-chest-bench-press')
  await workout.getByRole('spinbutton', { name: '重量（kg）', exact: true }).fill('20')
  await workout.getByRole('spinbutton', { name: '回数', exact: true }).fill('10')
  await workout.getByRole('button', { name: '＋ セットを追加', exact: true }).tap()
  await expect(card).toContainText('今日 +50 XP')
  for (const metric of ['最大重量', '最大回数', '総挙上量']) await expect(card).toContainText(metric)
  await expect(card).toContainText('ベンチプレス')
  await card.scrollIntoViewIfNeeded()
  if (process.env.RECAP_SCREENSHOTS) await page.screenshot({ path: '/home/ubuntu/screens/recap-pr.png' })
  await page.reload()
  await expect(card).toContainText('今日 +50 XP')
  await page.clock.fastForward(61_000)
  await expect(card).toContainText('2026.06.04')
  await expect(card).toContainText('まだ今日の記録はありません')
  await expect(card).toContainText('今日 +0 XP')
  await expect(card).not.toContainText('ベンチプレス')
})

test('demo recap never reads real records', async ({ page }) => {
  await page.addInitScript(() => {
    localStorage.setItem('habit-tracker:xp:v1', JSON.stringify({ totalXp: 999999, awarded: {} }))
    localStorage.setItem('habit-tracker:workout-sets:v1', 'invalid private data')
    localStorage.setItem('habit-tracker:study-time:v1', 'invalid private data')
  })
  await page.goto('./?demo=1')
  const card = page.getByRole('region', { name: '今日の締め', exact: true })
  await expect(card).toContainText('スクワット')
  await expect(card).not.toContainText('999999')
  await expect(card.getByRole('alert')).toHaveCount(0)
})
