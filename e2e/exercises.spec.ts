import { expect, test } from '@playwright/test'

test('モバイルで種目を部位で絞り込み、追加・編集して保存できる', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('./')
  await page.getByRole('button', { name: '種目', exact: true }).click()
  const filters = page.getByRole('group', { name: '部位で絞り込み' })
  await filters.getByRole('button', { name: '背中', exact: true }).click()
  await expect(page.getByTestId('exercise-item')).toHaveCount(3)
  await expect(page.getByTestId('exercise-item').first()).toContainText('懸垂')
  await page.getByRole('button', { name: '＋ 種目を追加する' }).click()
  await expect(page.getByRole('button', { name: '保存する' })).toBeDisabled()
  await page.getByLabel('種目名', { exact: true }).fill('ダンベルロウ')
  await page.getByRole('button', { name: '保存する' }).click()
  await expect(page.getByTestId('exercise-item')).toHaveCount(4)
  await page.getByRole('button', { name: 'ダンベルロウを編集' }).click()
  await page.getByLabel('種目名', { exact: true }).fill('自重ロウ')
  await page.getByLabel('部位', { exact: true }).selectOption('arms')
  await page.getByLabel('自重種目（回数だけで記録）').check()
  await page.getByRole('button', { name: '保存する' }).click()
  await expect(page.getByTestId('exercise-item')).toHaveCount(3)
  await expect(page.getByTestId('exercise-item').last()).toContainText('自重ロウ')
  await expect(page.getByTestId('exercise-item').last()).toContainText('腕 · 自重')
  await filters.getByRole('button', { name: '胸', exact: true }).click()
  await expect(page.getByTestId('exercise-item')).toHaveCount(2)
  await page.reload()
  await page.getByRole('button', { name: '種目', exact: true }).click()
  await filters.getByRole('button', { name: '腕', exact: true }).click()
  await expect(page.getByTestId('exercise-item').last()).toContainText('自重ロウ')
})
