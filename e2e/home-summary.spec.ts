import { expect, test } from '@playwright/test'

test('fresh default habits do not duplicate dedicated workout and study items', async ({ page }) => {
  await page.goto('./')
  const summary = page.getByRole('region', { name: '今日の記録' })
  await expect(summary.getByRole('button')).toHaveText(['筋トレ →', 'シャドテン →', 'スピフル →'])
  await expect(page.getByTestId('habit-item')).toHaveCount(2)
})

test('home links to inputs and updates unrecorded items, XP and completion after saving', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.addInitScript(() => {
    localStorage.setItem('habit-tracker:v1', JSON.stringify({ habits: [], logs: [] }))
  })
  await page.goto('./')
  const summary = page.getByRole('region', { name: '今日の記録' })
  const xp = page.getByRole('region', { name: 'レベルとXP' })
  await expect(summary.getByRole('heading', { name: '未記録の項目' })).toBeVisible()
  await expect(xp).toContainText('レベル 1')
  await expect(xp.getByRole('progressbar')).toBeInViewport()
  await expect(summary.getByRole('button', { name: 'スピフル →' })).toBeInViewport()
  await expect(summary).toContainText('0日連続')
  if (process.env.HOME_SCREENSHOTS) await page.screenshot({ path: '/home/ubuntu/screenshots/home-unrecorded.png' })
  for (const service of ['シャドテン', 'スピフル']) {
    await summary.getByRole('button', { name: `${service} →` }).tap()
    const input = page.getByRole('spinbutton', { name: `${service}（分）` })
    await expect(input).toBeFocused()
    await input.fill('15')
    await page.getByRole('button', { name: `${service}を保存` }).tap()
    await expect(summary.getByRole('button', { name: `${service} →` })).toHaveCount(0)
  }
  await expect(xp).toContainText('累計 20 XP')
  await summary.getByRole('button', { name: '筋トレ →' }).tap()
  await expect(page.locator('#workout-exercise')).toBeFocused()
  await page.locator('#workout-exercise').selectOption('preset-chest-bench-press')
  const workout = page.getByRole('region', { name: '今日の筋トレ' })
  await workout.getByRole('spinbutton', { name: '重量（kg）', exact: true }).fill('20')
  await workout.getByRole('spinbutton', { name: '回数', exact: true }).fill('10')
  await workout.getByRole('button', { name: '＋ セットを追加', exact: true }).tap()
  await expect(summary).toContainText('達成済み')
  await expect(summary).toContainText('1日連続')
  await expect(xp).toContainText('累計 30 XP')
  await expect(xp.getByRole('progressbar')).toHaveAttribute('value', '30')
  await expect(summary.getByRole('button')).toHaveCount(0)
  await page.evaluate(() => window.scrollTo(0, 0))
  if (process.env.HOME_SCREENSHOTS) await page.screenshot({ path: '/home/ubuntu/screenshots/home-done.png' })
})
