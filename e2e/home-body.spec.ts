import { expect, test } from '@playwright/test'

test('ホームの測定値は初期非表示、設定を再起動後も保持し、デモと分離する', async ({ page, context }) => {
  await page.goto('./')
  await page.getByTestId('nav-body').click()
  await page.getByTestId('body-weight-input').fill('77.7')
  await page.getByTestId('body-fat-input').fill('22.2')
  await page.getByTestId('body-save-button').click()
  await expect(page.getByTestId('body-item')).toContainText('77.7 kg')
  const original = await page.evaluate(() => ({ body: localStorage.getItem('habit-tracker:body:v1'), habits: JSON.parse(localStorage.getItem('habit-tracker:v1')!) }))
  await page.getByTestId('nav-record').click()
  await expect(page.getByTestId('home-body-values')).toHaveCount(0)
  expect(await page.locator('main').ariaSnapshot()).not.toContain('77.7')
  await page.getByText('ホームの表示設定').click()
  await page.getByRole('checkbox').check()
  await expect(page.getByTestId('home-body-values')).toContainText('77.7 kg')
  await page.reload()
  await expect(page.getByTestId('home-body-values')).toContainText('22.2 %')
  const reopened = await context.newPage()
  await reopened.goto('./')
  await expect(reopened.getByTestId('home-body-values')).toContainText('77.7 kg')
  await reopened.close()
  await page.goto('./?demo=1')
  await expect(page.getByTestId('home-body-values')).toHaveCount(0)
  await page.getByText('ホームの表示設定').click()
  await page.getByRole('checkbox').check()
  await expect(page.getByTestId('home-body-values')).toContainText('kg')
  await expect(page.getByTestId('home-body-values')).not.toContainText('77.7')
  await page.getByRole('checkbox').uncheck()
  await page.goto('./')
  await expect(page.getByTestId('home-body-values')).toContainText('77.7 kg')
  await page.getByText('ホームの表示設定').click()
  await page.getByRole('checkbox').uncheck()
  await page.reload()
  await expect(page.getByTestId('home-body-values')).toHaveCount(0)
  expect(await page.locator('main').ariaSnapshot()).not.toContain('22.2')
  await page.getByTestId('nav-body').click()
  await expect(page.getByTestId('body-item')).toContainText('77.7 kg ／ 22.2%')
  const after = await page.evaluate(() => ({ body: localStorage.getItem('habit-tracker:body:v1'), habits: JSON.parse(localStorage.getItem('habit-tracker:v1')!) }))
  expect(after.body).toBe(original.body)
  expect(after.habits.habits).toEqual(original.habits.habits)
  expect(after.habits.logs).toEqual(original.habits.logs)
})
